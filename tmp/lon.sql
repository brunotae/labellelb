## 04. The most powerful slow-ageing habit

For all the cutting-edge bio-ingredients, one of the best-evidenced products for preventing photoageing is, perhaps surprisingly, sunscreen.

In a randomised controlled trial lasting four and a half years, people who used sunscreen daily showed less skin ageing than those who used it only when they felt they needed it.

![Daily sunscreen is a well-evidenced slow-ageing habit. (AI-generated image)](media/lbedit-longevity-sun-2611-1024.webp)

If you want to keep your skin healthy for longer, start with the basics:

- Broad-spectrum sunscreen, SPF 30 or higher
- Barrier protection and enough moisture
- Minimal over-exfoliation and irritation
- Enough sleep and balanced nutrition
- Care suited to your own skin

The future of your skin may start not with an expensive jar of cream but with small habits repeated every day.

## 05. On the line between cosmetics and medicines

As the longevity market grows, the language used to describe efficacy is becoming a real issue.

In the United States, advertising that claims to act on specific physiological functions or genes can lead to a product being classified as a drug.

In Korea, advertising that leads consumers to mistake a cosmetic for a medicine is prohibited.

A March 2025 review of online cosmetics advertising by the Ministry of Food and Drug Safety illustrates the problem:

- Advertisements reviewed: 200
- Violations found: 144
- Ads that could be mistaken for medicines: 83
- Share of violations involving medicine-like claims: 57.6%

Claims such as "cell regeneration effect" and "Botox cream you apply" were among the cases flagged.

Cosmetic brands entering global markets need not only innovative ingredients but objective evidence of efficacy and an understanding of each country's regulations.


## 02. Skin ageing starts in the cell

Skin-ageing research is focusing on biological mechanisms such as cellular energy metabolism, oxidative stress and protein synthesis.

![Skin-ageing research looks at cellular energy and metabolism. (AI-generated image)](media/lbedit-longevity-cell-2611-1024.webp)

**Sirtuins**

A family of proteins involved in regulating cell metabolism and stress responses.

**AMPK**

An enzyme that senses a cell's energy status and regulates metabolism.

**mTOR**

A signalling pathway involved in cell growth, protein synthesis and autophagy.

Alongside these mechanisms, the beauty industry is showing growing interest in bio-ingredients such as NAD+, urolithin A, peptides and exosomes.

But a change in a biomarker in the lab does not mean ageing has slowed in real human skin.

Between an ingredient's potential and a finished product's efficacy lies a process: scientific validation.

## 03. Between science and marketing

Writing in Dermatology Times, dermatologist Dr Christopher Bunick raised the concern that skin longevity is being commercialised faster than it is being clinically validated.

Exosomes, stem-cell-derived products and some peptides in particular need sufficient clinical evidence to judge each product's efficacy and safety.

Urolithin A is drawing attention in research on ageing and cell function, but results from oral studies cannot simply be read as the efficacy of a cosmetic applied to the skin.

When choosing a new skincare product, these questions matter more than the ingredient's name:

- Was it tested on real people?
- Was the finished product evaluated, not just the raw ingredient?
- What was measured: elasticity, hydration, barrier function?
- Have long-term effects and safety been confirmed?

> An ingredient with a scientific name is not necessarily a scientifically proven cosmetic.


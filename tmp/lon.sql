## 01. 글로벌 뷰티 기업들이 주목하는 피부 장수 과학

에스티로더 컴퍼니즈는 2026년 11월 중국국제수입박람회(CIIE)에서 피부 장수 과학 플랫폼 'Mastering Skin Longevity'를 발표했다.

랑콤 역시 지난 3월 미국피부과학회(AAD) 연례 학술대회에서 '앱솔뤼 롱제비티 MD'를 선보였다.

이노바 마켓 인사이트의 시장 조사에 따르면,

- 롱제비티를 표방하는 퍼스널케어 신제품 출시 연평균 41% 증가
- 소비자의 66%가 롱제비티라는 개념에 긍정적인 인식

이러한 변화는 화장품 산업이 피부 표면의 아름다움을 넘어 생명과학과 바이오테크를 새로운 성장 동력으로 바라보고 있음을 보여준다.

## 02. 피부 노화는 세포에서 시작된다

피부 노화 연구에서는 세포의 에너지 대사, 산화 스트레스, 단백질 합성 등 다양한 생물학적 메커니즘에 주목하고 있다.

![피부 노화 연구는 세포의 에너지와 대사에 주목한다. (AI 생성 이미지)](media/lbedit-longevity-cell-2611-1024.webp)

**Sirtuins | 서투인**

세포의 대사와 스트레스 반응 조절에 관여하는 단백질군.

**AMPK**

세포의 에너지 상태를 감지하고 대사를 조절하는 효소.

**mTOR**

세포의 성장, 단백질 합성 및 자가포식에 관여하는 신호전달 경로.

최근 뷰티 산업에서는 이러한 메커니즘과 함께 NAD+, 유로리틴 A, 펩타이드, 엑소좀 등 다양한 바이오 소재에 대한 관심이 높아지고 있다.

그러나 실험실에서 특정 생체 지표가 변화했다는 사실이 실제 사람의 피부 노화가 늦춰졌다는 의미는 아니다.

원료의 가능성과 완제품의 효능 사이에는 과학적 검증이라는 과정이 필요하다.

## 03. 과학과 마케팅 사이

피부과 전문의 크리스토퍼 버닉 박사는 Dermatology Times를 통해 피부 롱제비티의 상업화 속도가 임상적인 검증보다 빠르다는 문제를 제기했다.

특히 엑소좀, 줄기세포 유래 제품, 일부 펩타이드 등은 제품별 효능과 안전성을 평가할 충분한 임상적 근거가 필요하다.

유로리틴 A 역시 신체 노화 및 세포 기능 연구에서 관심을 받고 있지만, 경구 섭취 연구 결과를 바르는 화장품의 효능으로 그대로 해석할 수는 없다.

새로운 화장품을 선택할 때는 성분의 이름보다 다음과 같은 질문이 중요하다.

- 실제 사람을 대상으로 시험했는가?
- 원료가 아닌 완제품을 평가했는가?
- 피부 탄력, 수분, 장벽 기능 등 무엇을 측정했는가?
- 장기적인 효과와 안전성이 확인되었는가?

> 과학적인 이름을 가진 성분이 반드시 과학적으로 검증된 화장품을 의미하지는 않는다.


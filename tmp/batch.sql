## Canada Is Not One Market

Building an export strategy on national growth figures alone is a risk.

Even within Canada, interest in K-beauty varies by region. Ontario and British Columbia are the key consumer markets, while Quebec shows comparatively lower purchasing levels.

That leaves brands with a choice: scale quickly where demand is already established, or build new demand where the market remains underdeveloped.

LB EDIT's view is that new entrants are better served by first securing regional consumer response and repurchase data, rather than chasing national distribution.

What matters is not the size of the retail network, but how well the product actually sells within it.

## Beauty Needs a Passport, Too

### The invisible passport of beauty.

Consumers see colour, scent, texture and packaging. Overseas buyers look at the paperwork behind them.

Ingredient specifications, product safety, labels that meet local regulations, details of the responsible importer. These invisible elements are what earn a product its place on a global shelf.

In Canada, manufacturers and importers must submit a Cosmetic Notification Form to Health Canada within 10 days of first selling a cosmetic.

Crucially, notification does not mean Health Canada has approved the product or certified its safety.

In 2026, fragrance allergen labelling requirements are also being phased in. For brands, that is reason to revisit everything from ingredient and fragrance disclosures to packaging production and local import agreements.

A product sold in Korea cannot necessarily enter every overseas market with the same label and the same marketing claims. Sunscreens and products making therapeutic claims, in particular, may fall under a different regulatory framework from ordinary cosmetics.

**Product quality gives a brand a reason to enter the market; regulatory compliance earns it the right to stay.**


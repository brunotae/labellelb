With Korea's aesthetic medicine, pharmacies and cosmetics industry all in the spotlight, understanding the role each one plays matters more than ever.

Clinics diagnose and treat, pharmacists guide the use of medicines, and cosmetics support sensible daily skincare. When those professional boundaries are respected, medical tourism and K-beauty can become experiences people trust even more.

## 07. Six Questions to Ask Before You Shop in Seoul

### The intelligent traveler's guide.

![A traveller receives guidance on use and precautions directly from a pharmacist. Good choices begin with accurate advice. (AI-generated image)](media/lbedit-pharmacy-consult-2611-1024.webp)

1. **IDENTIFY** — Check the packaging to see whether it is an OTC medicine, a quasi-drug or a cosmetic.
2. **DISCLOSE** — Tell the pharmacist about any medication you take, allergies, underlying conditions, and whether you are pregnant or breastfeeding.
3. **UNDERSTAND** — Ask for the amount, frequency, duration of use and precautions to be explained in a language you understand.
4. **CONSULT** — If you have just had a dermatology procedure, check with your medical team before using anything new.
5. **CHECK** — Look up your home country's rules on bringing in medicines, including permitted ingredients and quantity limits.
6. **CONSIDER** — Put your own skin and your actual needs ahead of trends and recommendation videos.

A good shopping trip isn't measured by the size of your basket. It's measured by how well you understand what's in it.


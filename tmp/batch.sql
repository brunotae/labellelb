## 57%: The Numbers Behind a New Order

According to NielsenIQ, K-beauty sales in Canada reached $164 million in 2025, up 57% year on year.

Growth is coming not only from established names such as Laneige, COSRX and Dr.Jart+, but also from Beauty of Joseon, SKIN1004, Ma:nyo, Torriden and d'Alba.

What stands out is how the market grew. Not by raising prices, but by multiplying the points where brands meet their customers.

In 2025, online channels accounted for more than 40% of sales. Yet the next growth opportunity now lies in the expansion of physical retail.

In beauty, shelf space is a finite resource. Every new brand that arrives is competing with incumbents for the shopper's choice.

Korean beauty is now moving to the centre of that contest.


## 04. PDRN, 같은 이름이 같은 효과를 의미하지 않는다

### The difference is in the science.

최근 K-뷰티 산업에서 주목받는 성분 중 하나는 PDRN이다. 의료미용에 대한 관심이 높아지면서 PDRN을 함유한 화장품 역시 해외 소비자들의 주목을 받고 있다.

그러나 여기서 반드시 구분해야 할 것이 있다.

의료기관에서 사용하는 주사제와 피부 표면에 사용하는 화장품은 동일한 제품이 아니다. 사용 경로, 제형, 성분 함량, 허가 목적, 효과를 평가하는 기준이 서로 다르다.

![같은 성분명 뒤에도 서로 다른 과학이 있다. 제형과 함량, 허가 목적이 효과를 가른다. (AI 생성 이미지)](media/lbedit-pharmacy-lab-2611-1024.webp)

화장품에 의료 시술과 유사한 성분명이 표시돼 있다고 해서 시술과 동일한 효과를 기대할 수는 없다. 이러한 구분은 PDRN뿐 아니라 의료미용 분야에서 사용되는 성분을 활용한 화장품 전반에도 적용된다.

성분의 인기가 높아질수록 소비자에게는 더 정확한 설명이 필요하다. 그리고 브랜드에는 더 높은 수준의 책임이 요구된다.


### What overseas buyers want now

In international distribution, signing a famous brand is no longer enough.

LB EDIT believes K-beauty brands and global distributors should focus on five metrics.

1. **Sell-through** — Units actually sold to consumers, not units shipped to the retailer.
2. **Repurchase** — The share of customers who choose the same product again after their first purchase.
3. **Retail Readiness** — How prepared a brand is for retail: local compliance, packaging, pricing policy.
4. **Supply Reliability** — The ability to supply authentic product consistently and replenish stock on time.
5. **Brand Equity** — The value that makes consumers choose a brand without heavy discounting or a momentary viral spike.

These metrics are also leverage in negotiations with overseas buyers.

Real sales records can outweigh a brand deck, conversion rates can outweigh follower counts, and steady repurchase data can outweigh a moment of hype.


## 06. From the Dermatologist to the Pharmacy: A New Kind of Journey

### The journey beyond treatment.

Travellers who head to a pharmacy after a dermatology consultation or procedure in Korea have more to consider than the average beauty shopper. Skin that has just been treated may not behave as it normally does.


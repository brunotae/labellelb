## 05. CARE WITHOUT BORDERS

### Can care continue after the plane takes off?

Patients finish their treatment in Seoul and fly home to São Paulo, to Dubai, to Ulaanbaatar. Once again, thousands of kilometres separate them from Korea.

Their medical questions, however, do not disappear with the distance.

There may come a moment when recovery takes an unexpected turn, when a follow-up consultation is needed, or when they have to explain their treatment to a local doctor.

An amendment to the Act on Support for Overseas Expansion of Medical Services and Attraction of Foreign Patients, promulgated in May 2026, opens up new possibilities. It establishes a legal basis for telemedicine for international patients.

The amended law covers pre-arrival consultations and post-return aftercare, ongoing monitoring, counselling and education, as well as diagnosis and prescriptions. Even first-time international patients may be eligible.

The law is scheduled to take effect in 2027, one year after promulgation. Specific procedures and conditions will need to be confirmed through enforcement decrees, and the medical regulations of the patient's country of residence must also be taken into account.

Legalising telemedicine is not merely a matter of technology that lets patients see a doctor on screen. Its significance lies in the possibility that the relationship between patient and clinic need no longer end with a single visit.

> Continuity of Care.

It is a concept set to matter more and more in the global medical tourism market.

## 06. THE PATIENT'S EDIT

### For those planning treatment in Seoul

A good medical trip does not begin with a treatment booking and end with a return ticket.

International patients preparing to visit Korea should keep the following five points in mind.

1. **Choose the right medical institution.** Confirm that the clinic is registered to treat international patients, and consult thoroughly with your doctor.
2. **Make room for recovery.** Give your recovery schedule as much weight as your procedure schedule. Follow your medical team's judgement on the length of your stay and when it is safe to fly.
3. **Stay close to care.** Look beyond a hotel's star rating: check its distance from the hospital, whether long stays are possible, and how emergencies are handled.
4. **Know who to call.** Before you leave, confirm the clinic's aftercare contact, the languages available and how to reach them.
5. **Bring your medical records home.** Secure the medical records, prescription details and recovery guidance you need, and be prepared to see a local doctor if any problem arises after you return.


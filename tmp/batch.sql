Over-the-counter medicines can be bought without a doctor's prescription, but they are still medicines.

Quasi-drugs are items defined by law, such as protective face masks and certain hygiene products.

Cosmetics are products that keep the skin clean and cared for. Functional cosmetics, too, are distinct from medicines intended to treat disease.

Marketing terms such as "dermocosmetic" or "medical cosmetic" do not, in themselves, mean a product is a medicine.


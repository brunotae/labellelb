## 02. 196.1%, 하나의 유행으로 설명하기 어려운 숫자

### Follow the money.

연합뉴스가 한국관광데이터랩의 카드 결제 데이터를 분석한 결과, 2026년 1~9월 외국인의 의료 관련 소비액은 1조 8,398억 원으로 전년 동기 대비 57.9% 증가했다.

같은 기간 약국 소비액은 196.1% 늘었다. 전체 의료 관련 소비액의 증가율보다 약국 소비액 증가율이 훨씬 높았다는 점이 흥미롭다. 의료 관련 소비에서 약국이 차지하는 비중도 6.66%에서 12.49%로 확대됐다.

공급 역시 변화하고 있다. 데일리팜에 따르면 2025년 9월부터 2026년 6월까지 서울 중구에서만 외국인 고객을 겨냥한 약국 28곳이 새롭게 문을 열었다.

약국은 이제 일부 여행자에게 의약품을 구매하는 장소를 넘어 한국의 피부 관리 문화를 경험하는 공간이 되고 있다.

물론 카드 결제 데이터에는 화장품뿐 아니라 의약품 등 다양한 구매가 포함될 수 있다. 약국 소비 증가 전체를 화장품 매출 증가로 해석해서는 안 된다.

그럼에도 이 변화는 글로벌 뷰티 산업에 중요한 질문을 던진다.

소비자는 왜 화장품 매장뿐 아니라 약국에서도 아름다움의 해답을 찾기 시작했을까.


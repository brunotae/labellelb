## 04. PDRN: The Same Name Doesn't Mean the Same Effect

### The difference is in the science.

PDRN is one of the ingredients drawing the most attention in K-beauty right now. As interest in aesthetic medicine grows, cosmetics containing PDRN are catching the eye of shoppers abroad as well.

But one distinction is essential.

An injectable used in a clinic and a cosmetic applied to the surface of the skin are not the same product. They differ in route of application, formulation, concentration, approved purpose and the standards by which their effects are assessed.

![Behind the same ingredient name lie different sciences: formulation, concentration and approved purpose determine the effect. (AI-generated image)](media/lbedit-pharmacy-lab-2611-1024.webp)

A cosmetic that lists an ingredient also used in medical procedures cannot be expected to deliver the results of that procedure. The same applies to cosmetics built on any ingredient borrowed from aesthetic medicine, not just PDRN.

The more popular an ingredient becomes, the more clearly it needs to be explained to consumers, and the more responsibility falls on the brands that sell it.


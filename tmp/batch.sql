## 05. First Time? Start With Questions, Not Procedures

### The intelligent approach to aesthetics.

For a man visiting a dermatologist for the first time, the most useful thing may not be a list of popular treatments. It is understanding his own concerns and communicating them clearly to the medical team.

1. **What do I want to preserve?** Describe not only what you would like to improve, but the features and impression you want to keep.
2. **What does my skin actually need?** Clarify your main concerns, whether oiliness, pores, texture, wrinkles or firmness, and have them assessed by a medical professional.
3. **What are the alternatives?** Distinguish what can be addressed with skincare from what calls for a medical procedure, and consider the option of no procedure at all.
4. **What are the risks?** Alongside the expected benefits, make sure you fully understand the side effects, recovery time and how results vary between individuals.
5. **What happens afterwards?** Confirm when you can return to normal life and how aftercare will work. If you are travelling from abroad, arrange how to contact the clinic once you are home and which medical records you will need.

**A good consultation is not a session for agreeing to more procedures. It is time spent making the right choice for you, with fuller information.**


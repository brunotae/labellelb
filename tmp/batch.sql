## 06. 피부과에서 약국으로 이어지는 새로운 여행

### The journey beyond treatment.

한국에서 피부과 상담과 시술을 받은 뒤 약국을 방문하는 여행자들에게는 일반적인 뷰티 쇼핑과 다른 고려 사항이 있다. 시술 직후의 피부는 평소와 상태가 다를 수 있기 때문이다.

평소 사용하던 화장품도 시술 후에는 자극을 유발할 수 있으며, SNS에서 인기를 얻은 연고가 모든 피부 상태에 적합한 것도 아니다. 특히 레이저, 필링, 주사 시술 이후에는 새로운 제품을 사용하기 전에 담당 의료진의 안내를 확인해야 한다.

의료관광의 경험은 시술이 끝나는 순간에 완성되지 않는다. 회복 과정과 일상적인 피부 관리, 귀국 이후의 의료적 소통까지 연결돼야 한다.

한국의 의료미용 산업과 약국, 화장품 산업이 함께 주목받는 지금, 이들 사이의 역할을 정확하게 이해하는 것이 더욱 중요해지고 있다.

의료기관은 진료와 치료를 담당하고, 약사는 의약품 사용을 안내하며, 화장품은 적절한 일상 피부 관리를 지원한다. 이러한 전문성의 경계가 존중될 때 의료관광과 K-뷰티는 더욱 신뢰할 수 있는 경험으로 발전할 수 있다.


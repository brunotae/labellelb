## 01. Why does the face change when the weight comes off?

### Facial volume is not determined by skin alone

The shape of our face is influenced by many tissues: skin, subcutaneous fat, muscle, ligaments and bone.

Subcutaneous fat in particular plays an important role in giving volume to the cheeks and temples and softening the contours of the face.

When we lose weight, we can lose fat from the face as well as the body.

With significant weight loss, changes like these may appear:

- Cheeks and temples that look more sunken than before
- Nasolabial folds and lines around the mouth that look relatively more pronounced
- Skin along the jawline and neck that looks looser
- Changes in the overall volume and contour of the face

Add age-related loss of skin elasticity, and the face can look more tired, or older, than it really is.

These changes do not appear the same way in everyone who loses weight.

They vary widely with age, starting weight, how much weight is lost and the condition of the skin.


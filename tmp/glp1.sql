## 02. 오젬픽 페이스, 정말 약물 때문일까?

### 전문가들이 주목하는 것은 체중 감소와 다양한 생리적 변화다

2026년 10월 Reuters는 GLP-1 체중감량 약물의 확산과 함께 새롭게 주목받는 피부·미용 시장을 보도했다.

보도에 참여한 전문가들은 이른바 '오젬픽 페이스'를 약물 자체의 직접적인 영향으로 단정해서는 안 된다고 설명했다.

얼굴 볼륨 감소는 체중감량 과정에서 나타날 수 있는 지방량 변화와 관련이 있으며, 연령과 호르몬 변화, 영양 상태 등도 함께 고려해야 한다는 것이다.

GLP-1 계열 약물은 식욕과 포만감 등에 작용해 체중 감소를 돕는다.

하지만 약물 사용 후 관찰되는 얼굴 변화가 모두 약물의 직접적인 피부 작용 때문인지는 아직 충분히 규명되지 않았다.

따라서 'GLP-1 약물이 얼굴을 늙게 만든다'는 표현보다는 **'체중감량 과정에서 얼굴의 지방과 피부 윤곽이 달라질 수 있다'**는 설명이 더 정확하다.

중요한 것은 약물 사용 여부만이 아니라 체중 변화와 전반적인 건강 상태를 함께 살피는 것이다.

## 03. 글로벌 미용 시장은 이미 움직이고 있다

### 체중감량 이후의 피부관리가 새로운 시장으로 부상하다

체중감량 약물의 확산은 제약 산업을 넘어 글로벌 의료미용 및 화장품 산업에도 영향을 주고 있다.

Reuters에 따르면 갈더마(Galderma), 로레알(L'Oréal), 나투라(Natura) 등 글로벌 뷰티 기업들은 체중감량 이후 나타나는 피부 변화에 주목하며 관련 제품과 의료미용 솔루션을 검토하고 있다.

보도에 인용된 보스턴컨설팅그룹(BCG)의 전망에 따르면 GLP-1 관련 임상 미용 시술 시장은 향후 5년간 약 7억 달러에서 20억 달러 규모로 성장할 가능성이 제시됐다.

이는 시장 전망치이지 확정된 매출이나 치료 효과를 의미하지는 않는다.

한편 국제미용성형외과학회(ISAPS)의 2025년 글로벌 조사에서는 지방흡입 시술 건수가 전년 대비 약 11.4% 감소한 것으로 집계됐다.

다만 이 변화가 GLP-1 약물 사용 증가 때문에 발생했다고 단정할 수는 없다.

그럼에도 체중감량 이후 얼굴과 신체 윤곽에 대한 새로운 미용 상담 수요가 나타나고 있다는 점은 주목할 만하다.

의료미용 시장에서는 단순한 체형 변화뿐 아니라 감량 이후의 피부 상태와 윤곽을 어떻게 관리할 것인지가 새로운 관심 영역이 되고 있다.

## 04. 화장품으로 얼굴 볼륨을 되돌릴 수 있을까?

### 스킨케어와 의료미용의 역할은 다르다

체중감량 이후 피부가 건조하거나 탄력이 떨어진 것처럼 느껴진다면 보습과 피부 장벽 관리가 도움이 될 수 있다.

히알루론산, 글리세린, 세라마이드 등은 피부 보습과 장벽 관리에 활용되는 대표적인 성분이다.

![체중감량 중에도 보습과 피부 장벽 관리는 중요하다. (AI 생성 이미지)](media/lbedit-glp1-skincare-2611-1024.webp)

레티노이드 계열 성분은 종류와 농도에 따라 피부결이나 잔주름 개선에 도움을 줄 수 있지만, 자극 가능성과 사용상 주의사항을 고려해야 한다.

그러나 여기서 중요한 구분이 있다.

**화장품은 체중감량으로 감소한 얼굴의 피하지방을 복원하거나 얼굴의 해부학적 구조를 재형성하지 못한다.**

보습으로 피부가 일시적으로 더 매끄럽고 탄탄해 보일 수는 있지만, 이는 실제 얼굴 지방량을 회복시키는 것과는 다르다.

따라서 '볼륨 회복', '얼굴 지방 재생', '수술 수준의 리프팅'과 같은 표현을 접할 때는 해당 제품의 실제 효능과 근거를 확인할 필요가 있다.

반면 필러, 콜라겐 생성 촉진을 목적으로 하는 주사 시술, 에너지 기반 의료기기 등은 의료진의 평가를 바탕으로 고려할 수 있는 의료적 접근이다.

하지만 모든 시술이 모든 환자에게 적합한 것은 아니다.

시술 종류에 따라 부종, 멍, 염증, 감염, 혈관 관련 합병증 등 위험이 발생할 수 있으므로 충분한 의료 상담이 필요하다.

## 05. 체중감량 중이라면 피부관리는 어떻게 해야 할까?

### 시술보다 먼저 확인해야 할 네 가지

2026년 SCALE 학술회의에서도 GLP-1 사용자의 피부 변화와 미용 시술에 대한 논의가 이루어졌다.

핵심은 체중감량의 진행 단계와 개인의 건강 상태를 고려한 맞춤형 접근이다.

**첫째, 체중 변화 추이를 확인한다.**

체중이 계속 감소하는 동안에는 얼굴의 볼륨과 윤곽도 달라질 수 있다.

따라서 얼굴 볼륨 교정이나 수술적 치료를 계획한다면 체중이 어느 정도 안정되었는지 의료진과 상의하는 것이 좋다.

모든 피부 시술을 반드시 체중 안정 이후로 미뤄야 한다는 의미는 아니다.

**둘째, 영양 상태를 점검한다.**

체중감량 과정에서 음식 섭취량이 지나치게 줄면 단백질과 필수 영양소를 충분히 섭취하지 못할 수 있다.

영양 부족은 전반적인 건강과 상처 회복에 영향을 줄 수 있으므로, 필요하다면 의료진 또는 영양 전문가의 평가를 받는 것이 좋다.

**셋째, 복용 약물을 의료진에게 알린다.**

GLP-1 계열 약물은 위 배출에 영향을 줄 수 있어 진정이나 전신마취가 필요한 시술 전에는 복용 사실을 반드시 알려야 한다.

약물을 임의로 중단하거나 복용 일정을 변경하지 말고, 담당 의료진의 개별적인 지침을 따라야 한다.

**넷째, 기본적인 피부관리를 유지한다.**

체중감량 중에도 자외선 차단, 충분한 보습, 자극을 최소화한 세안 등 기본적인 스킨케어는 중요하다.

특히 피부가 건조하거나 예민해졌다면 여러 기능성 제품을 한꺼번에 사용하기보다는 피부 상태에 맞는 간단한 루틴을 유지하는 것이 도움이 될 수 있다.

## 06. 웰에이징의 기준이 달라지고 있다

### 체중보다 중요한 것은 건강한 변화


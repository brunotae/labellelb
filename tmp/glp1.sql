## 01. 체중은 줄었는데 얼굴은 왜 달라질까?

### 얼굴의 볼륨은 피부만으로 결정되지 않는다

우리 얼굴의 형태는 피부, 피하지방, 근육, 인대, 뼈 등 다양한 조직의 영향을 받는다.

그중 피하지방은 볼과 관자 부위의 볼륨을 형성하고 얼굴 윤곽을 부드럽게 만드는 데 중요한 역할을 한다.

체중이 감소하면 신체의 지방뿐 아니라 얼굴의 지방량도 줄어들 수 있다.

특히 체중이 크게 감소하면 다음과 같은 변화가 나타날 수 있다.

- 볼과 관자 부위가 이전보다 꺼져 보이는 현상
- 팔자주름과 입 주변 주름이 상대적으로 두드러지는 변화
- 턱선과 목 주변 피부가 느슨해 보이는 현상
- 얼굴의 전체적인 볼륨과 윤곽 변화

여기에 나이에 따른 피부 탄력 감소가 겹치면 실제 나이보다 피곤하거나 나이 들어 보이는 인상을 줄 수 있다.

다만 이러한 변화는 모든 체중감량 환자에게 동일하게 나타나지 않는다.

개인의 연령, 감량 전 체중, 감량 정도, 피부 상태에 따라 차이가 크다.


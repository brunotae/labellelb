PDRN, exosomes, skin boosters.

Terms once heard only in medical aesthetics are becoming the new language of the global beauty market.

As medical aesthetics and cosmetics overlap more, the products and technologies consumers encounter are becoming more varied.

But as important as an innovative ingredient is understanding how it is used.

According to data submitted by the Ministry of Food and Drug Safety to the National Assembly, 81 of 106 advertising violations for PDRN cosmetics were ads that could lead consumers to mistake a cosmetic for a medicine.

That is about 76.4% of all violations.

A cosmetic applied to the skin is not the same as an injection performed at a medical institution. Even with the same ingredient name, the method of use, approval standards and evidence for safety and efficacy can differ.

The closer beauty and medicine become, the more accurate information consumers need.


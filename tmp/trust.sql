**01. WHO — Who will perform my procedure?**

Have you checked the qualifications and specialty of the doctor who will actually treat you?

**02. WHAT — What will be used?**

Do you know the exact name of the procedure, the products used and their approved purpose?

**03. HOW MUCH — What will it really cost?**

Have you been told about the procedure fee, anaesthesia, VAT and any additional care costs?


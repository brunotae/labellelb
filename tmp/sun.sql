| When | What changed |
|---|---|
| 2025.12 | FDA proposes listing bemotrizinol |
| 2026.06 | FDA announces the new ingredient |
| 2026.08 | New rule takes effect |
| 2026.09 | Order removing two existing UV filters |
| 2027.09 | Removal of PABA and trolamine salicylate expected to take effect |
| 2028.02 | Bemotrizinol exclusivity expected to end |

The end of exclusivity is an estimate based on the published schedule.

In September 2026, the FDA decided to remove two existing UV filters, PABA and trolamine salicylate, from the OTC monograph.

Barring other changes, the monograph will list 15 sunscreen active ingredients from September 2027.

The US sun care market is adding new ingredients while re-evaluating the safety of existing ones.


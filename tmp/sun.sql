## 04. 시장은 열렸지만, 18개월의 독점 기간이 남아 있다

이번 FDA 결정에서 화장품 업계가 주목해야 할 또 하나의 핵심은 독점 판매권이다.

FDA는 비모트리지놀의 등재를 신청한 DSM Nutritional Products LLC와 해당 권리를 가진 라이선스 업체 등에 18개월간의 독점권을 부여했다.

따라서 모든 화장품 제조사가 신규 규정 시행 직후 해당 성분을 활용한 제품을 자유롭게 미국에서 판매할 수 있는 것은 아니다.

### 미국 선케어 규제 변화 타임라인

| 시점 | 주요 변화 |
|---|---|
| 2025.12 | FDA 비모트리지놀 등재 제안 |
| 2026.06 | FDA 신규 성분 허용 발표 |
| 2026.08 | 신규 규정 시행 |
| 2026.09 | 기존 자외선 차단 성분 2종 삭제 명령 |
| 2027.09 | PABA·Trolamine Salicylate 삭제 시행 예정 |

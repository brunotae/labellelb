**미국 전용 처방 개발**

한국 내수용과 미국 수출용 제품의 처방을 구분하고, 현지 규정에 적합한 자외선 차단 성분을 검토해야 한다.

**OTC 제조 역량 확보**

미국 의약품 제조관리기준과 관련 등록·제품 등재 요건을 충족할 수 있는 제조 파트너를 확보해야 한다.

**과학적 근거 중심의 마케팅**

SPF, 광범위 차단 성능, 내수성 등 제품의 실제 시험 결과를 기반으로 신뢰도를 구축해야 한다.

**프리미엄 B2B 유통 확대**

피부과, 의료미용 클리닉, 에스테틱숍 등 전문적인 제품 추천이 이루어지는 유통 채널도 검토할 필요가 있다.

**시장별 제품 포트폴리오 구축**

미국, 유럽, 한국, 중남미 등 국가별 규제와 소비자 특성을 반영해 제품 및 유통 전략을 차별화해야 한다.

## 07. 소비자와 해외 바이어가 확인해야 할 것

글로벌 시장에서 동일한 브랜드와 패키지가 반드시 동일한 성분을 의미하지는 않는다.

소비자는 제품을 선택할 때 자외선 차단 유효 성분, SPF, UVA 차단 표시, 사용기한 등을 확인하는 것이 좋다.

해외 바이어라면 다음 사항도 함께 검토해야 한다.

- 판매 대상 국가의 자외선 차단 성분 기준
- 수출용 제품의 전체 처방 및 성분표
- SPF·UVA 차단 관련 시험성적서
- 제조시설의 규제 적합성
- 현지 수입·유통 및 규제 대응 책임 주체
- 제품의 효능·효과에 관한 광고 표현

자외선 차단은 선크림에만 의존하기보다 모자, 선글라스, 보호 의류 등 다양한 방법을 함께 활용하는 것이 중요하다.


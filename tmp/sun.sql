## 07. What consumers and overseas buyers should check

In global markets, the same brand and packaging do not always mean the same ingredients.

Consumers should check the active UV filters, SPF, UVA protection labelling and expiry date.

Overseas buyers should also review:

- UV filter rules in the target market
- The full formula and ingredient list of the export product
- SPF and UVA test reports
- Regulatory compliance of the manufacturing site
- Who is responsible for import, distribution and regulatory affairs locally
- Advertising claims about efficacy

Sun protection works best when sunscreen is combined with hats, sunglasses and protective clothing.


## 04. The market is open, but an 18-month exclusivity remains

Another key point in the FDA decision is exclusivity.

The FDA granted 18 months of exclusivity to DSM Nutritional Products LLC, which requested the listing of bemotrizinol, and to its licensees.

So not every cosmetics manufacturer can freely sell bemotrizinol products in the US as soon as the new rule takes effect.


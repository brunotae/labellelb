## 01. 한국에서는 화장품, 미국에서는 의약품

한국과 미국의 선크림 시장을 이해하기 위해서는 먼저 제품을 바라보는 두 국가의 제도적 차이를 알아야 한다.

한국에서는 자외선 차단제를 기능성화장품으로 분류하지만, 미국에서는 일반의약품(OTC, Over-the-Counter Drug)으로 관리한다.

| 구분 | 한국 | 미국 |
|---|---|---|
| 제품 분류 | 기능성화장품 | 일반의약품(OTC) |
| 관리 기관 | 식품의약품안전처 | FDA |
| 자외선 차단 표시 | SPF·PA | SPF·Broad Spectrum |
| 제품 관리 | 기능성화장품 심사·보고 | OTC 의약품 관련 규정 |
| 시장 진출 | 국내 화장품 기준 | 미국 의약품 기준 충족 |

한국에서 판매되는 인기 선크림이라도 미국의 자외선 차단 성분 기준과 제조·시험·표시 요건을 충족하지 못하면 미국 시장에서 동일한 제품을 판매하기 어렵다.

글로벌 뷰티 시대에도 화장품의 국경은 여전히 존재하는 셈이다.

## 02. 비모트리지놀, 무엇이 특별한가?

**Bemotrizinol — The Next Generation of Sun Protection**

비모트리지놀은 BEMT라고도 불리는 유기 자외선 차단 성분이다. Tinosorb S와 PARSOL Shield 등의 상업명으로도 알려져 있다.

UVA와 UVB를 모두 차단할 수 있으며, 광안정성이 우수해 다양한 선케어 제품의 처방에 활용되고 있다.

주요 특징은 다음과 같다.

- UVA·UVB 광범위 자외선 차단
- 우수한 광안정성
- 낮은 전신 흡수 수준
- 다양한 선케어 제형 개발 가능성
- FDA 허용 최대 농도 6%


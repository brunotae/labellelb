UVA는 피부 광노화와 관련이 있으며, UVB는 일광화상의 주요 원인이다. 두 영역을 균형 있게 차단하는 것은 피부 건강과 장기적인 자외선 관리에 중요하다.

다만 선크림의 실제 사용감과 차단 효과는 특정 성분 하나가 아니라 전체 처방과 완제품의 시험 결과에 따라 달라진다.

## 03. 한국 선크림은 왜 미국에서 그대로 판매하기 어려울까?


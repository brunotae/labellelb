## 01. A cosmetic in Korea, a drug in the US

To understand the two markets, start with how each country classifies the product.

Korea classifies sunscreen as a functional cosmetic. The US regulates it as an over-the-counter (OTC) drug.

| | Korea | United States |
|---|---|---|
| Classification | Functional cosmetic | OTC drug |
| Regulator | Ministry of Food and Drug Safety | FDA |
| Sun protection labelling | SPF · PA | SPF · Broad Spectrum |
| Product control | Functional cosmetic review / report | OTC drug regulations |
| Market entry | Korean cosmetic standards | US drug requirements |

Even a best-selling Korean sunscreen cannot be sold unchanged in the US if it does not meet US rules on UV filters, manufacturing, testing and labelling.

Even in an age of global beauty, cosmetics still have borders.

## 02. What makes bemotrizinol special?

**Bemotrizinol — The Next Generation of Sun Protection**

Bemotrizinol, also called BEMT, is an organic UV filter, known by trade names such as Tinosorb S and PARSOL Shield.

It covers both UVA and UVB and is highly photostable, which makes it useful in a wide range of sun care formulas.

Key features:

- Broad-spectrum UVA and UVB protection
- Excellent photostability
- Low systemic absorption
- Room for many sun care textures
- Maximum concentration allowed by the FDA: 6%

UVA is linked to photoageing; UVB is the main cause of sunburn. Balanced protection across both matters for skin health and long-term sun care.

Still, how a sunscreen feels and how well it protects depend not on one ingredient but on the whole formula and on tests of the finished product.


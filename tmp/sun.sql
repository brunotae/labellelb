독점 기간 종료 시점은 현재 공개된 시행 일정에 따른 예상이다.

FDA는 2026년 9월 기존 자외선 차단 성분인 PABA와 트롤아민 살리실레이트를 OTC 모노그래프에서 제외하기로 결정했다.

이에 따라 다른 규제 변경이 없다면 2027년 9월 이후 모노그래프상 자외선 차단 유효 성분은 15종이 될 예정이다.

미국 선케어 시장은 새로운 성분을 받아들이는 동시에 기존 성분의 안전성도 재평가하고 있다.

